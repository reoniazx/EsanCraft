#!/usr/bin/env python3
# Modified for EsanCraft; original notices retained. See MODIFICATIONS.md.
"""Check or write change notices for text modified from the pinned SoundCraft base.

The index determines the release's modified files. --write also updates the working
copy, while preserving pre-existing unstaged edits. Never alter third-party licenses.
"""
import argparse
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
BASE = '7dc56a4'
MARKER = 'Modified for EsanCraft; original notices retained. See MODIFICATIONS.md.'
SKIP = {'LICENSE', 'LICENSE-MIT', 'LICENSE-APACHE', 'NOTICE', 'THIRD-PARTY-LICENSES.txt', 'MODIFICATIONS.md', 'docs/license-audit.md'}
TEXT = {'.rs', '.md', '.toml', '.sh', '.ps1', '.yml', '.yaml', '.py', '.lock', '.plist', '.wxs', '.xml', '.in', '.html', '.desktop'}

def git(*args, data=None):
    return subprocess.check_output(['git', *args], cwd=ROOT, input=data)

def paths():
    rows = git('diff', '--cached', '--name-status', '-M', BASE).decode().splitlines()
    for row in rows:
        status, *names = row.split('\t')
        if status.startswith('D') or status == 'R100':
            continue
        name = names[-1]
        if name in SKIP or name.startswith('assets/fonts/') or Path(name).suffix not in TEXT:
            continue
        yield name

def marked(name, text):
    if name == 'Cargo.lock':
        generated = ['# This file is automatically @generated by Cargo.', '# It is not intended for manual editing.']
        body = '\n'.join(line for line in text.splitlines() if line not in generated and line != '# ' + MARKER) + '\n'
        return '\n'.join([*generated, '# ' + MARKER]) + '\n' + body
    if MARKER in text:
        return text
    suffix = Path(name).suffix
    if suffix == '.rs':
        notice = '// ' + MARKER + '\n'
    elif suffix in {'.xml', '.plist', '.wxs', '.in', '.html'}:
        notice = '<!-- ' + MARKER + ' -->\n'
    elif suffix == '.md':
        notice = '> ' + MARKER + '\n\n'
    else:
        notice = '# ' + MARKER + '\n'
    if text.startswith('#!') or text.startswith('<?xml'):
        first, sep, rest = text.partition('\n')
        return first + sep + notice + rest
    return notice + text

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    missing = []
    for name in paths():
        staged = git('show', ':' + name).decode()
        updated = marked(name, staged)
        if updated == staged:
            continue
        missing.append(name)
        if args.write:
            p = ROOT / name
            p.write_text(marked(name, p.read_text()))
            oid = git('hash-object', '-w', '--stdin', data=updated.encode()).decode().strip()
            mode = git('ls-files', '-s', '--', name).decode().split()[0]
            subprocess.run(['git', 'update-index', '--cacheinfo', mode, oid, name], cwd=ROOT, check=True)
    if missing and not args.write:
        print('Modified text files missing change notices:\n' + '\n'.join(missing))
        return 1
    print('EsanCraft per-file modification notices:', 'updated ' + str(len(missing)) if args.write else 'OK')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
